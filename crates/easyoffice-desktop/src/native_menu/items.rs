//! Static custom menu item table (`ITEMS`) for the macOS native menu bar (`PD-102`, `PD-121`, `PD-250`).

use super::MenuItemSpec;

const fn item(
    id: &'static str,
    label: &'static str,
    accelerator: Option<&'static str>,
    action: &'static str,
) -> MenuItemSpec {
    MenuItemSpec {
        id,
        label,
        accelerator,
        action,
    }
}

/// A spreadsheet menu item that runs the page menu item `data-sheet-act="<act>"`.
macro_rules! sa {
    ($id:literal, $label:literal, $act:literal) => {
        item($id, $label, None, concat!("sheet-act:", $act))
    };
}
/// A slide menu item that runs the page menu item `data-slide-act="<act>"`.
macro_rules! sl {
    ($id:literal, $label:literal, $act:literal) => {
        item($id, $label, None, concat!("slide-act:", $act))
    };
}
/// A studio menu command item (`studio-cmd:<cmd>`).
macro_rules! sc {
    ($id:literal, $label:literal, $cmd:literal) => {
        item($id, $label, None, concat!("studio-cmd:", $cmd))
    };
}

/// An item of the spreadsheet's 조건부 서식 menu: it runs the page item `data-sheet-cf="<action>"`, and its id is
/// `format:cf-<action>`.
macro_rules! cf {
    ($label:literal, $action:literal) => {
        item(
            concat!("format:cf-", $action),
            $label,
            None,
            concat!("sheet-cf:", $action),
        )
    };
}

